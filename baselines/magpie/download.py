"""Download Swedish Magpie data from Hugging Face into data/raw/.

Run: uv run python -m baselines.magpie.download

Source: matsten/Magpie-SWE-Llama-3.3-70B-Instruct-V3-0324-responses, published with
"Synthetic Instruction Generation for Low-Resource Nordic Languages: Viability and Limitations
in LLM Instruction-Tuning" (LREC 2026, https://aclanthology.org/2026.lrec-1.838/).
Instructions were generated in Swedish with the Magpie pipeline (Xu et al., 2024) using
Llama-3.3-70B-Instruct and quality-filtered; responses were generated by DeepSeek-V3-0324.

LICENSE / KNOWN LIMITATION: the dataset card states no license. The instructions are Llama 3.3
output, so Meta's Llama 3.3 Community License likely applies to them: fine-tuning non-Llama
models (e.g. Gemma) is permitted, but a model trained on it that is distributed or made available
must have a name starting with "Llama" and display "Built with Llama". This must be reported as a
limitation of the baseline comparison.
"""
from __future__ import annotations

import json
from pathlib import Path

from datasets import load_dataset

RAW = Path(__file__).resolve().parent / "data/raw"

REPO = "matsten/Magpie-SWE-Llama-3.3-70B-Instruct-V3-0324-responses"
LICENSE = "Not stated (instructions from Llama 3.3; responses from DeepSeek-V3-0324)"


def main() -> None:
    dataset = load_dataset(REPO)
    RAW.mkdir(parents=True, exist_ok=True)
    for old in RAW.glob("*.parquet"):
        old.unlink()
    for split, data in dataset.items():
        data.to_parquet(RAW / f"{split}.parquet")
    (RAW / "source.json").write_text(json.dumps({"repo": REPO, "license": LICENSE}, indent=2) + "\n", encoding="utf-8")

    print(f"Source: {REPO} (license: {LICENSE})")
    print(f"Columns: {next(iter(dataset.values())).column_names}")
    for split, data in dataset.items():
        print(f"  {split}: {data.num_rows:,} rows")
    print(f"Total: {sum(d.num_rows for d in dataset.values()):,} rows -> {RAW}")


if __name__ == "__main__":
    main()
