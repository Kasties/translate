import json
import re
import wikipedia
import ollama
import tomllib
from tqdm import tqdm

def load_settings(config_path="example-settings.toml"):
    with open(config_path, "rb") as f:
        return tomllib.load(f)

def clean_json_response(content):
    content = content.strip()
    match = re.search(r'\[.*\]', content, re.DOTALL)
    if match:
        return match.group(0)
    return content

def generate_topics_batch(settings, topic_type, batch_size=20):
    model_name = settings["model"]["ollama"]["model"]
    system_prompt = settings["general"]["custom_system_prompt"]
    temperature = settings["general"]["topic_generation_temperature"]
    
    if topic_type == "general":
        user_instruction = (
            f"Please generate {batch_size} completely random topics. These can be about science, "
            "history, geography, philosophy, technology, or nature. "
            "CRITICAL INSTRUCTION: Each topic MUST be a specific noun or entity (1 to 4 words maximum in Swedish) "
            "that would make a perfect Wikipedia search query (e.g., 'Kvantfysik', 'Romerska riket', 'Fotosyntes'). "
            "Do NOT write full sentences. Do NOT write questions. Output ONLY a valid JSON list of these short strings. "
            "Do not include any other text, markdown formatting, or commentary."
        )
    else:
        culture_persona = settings["culture"]["prompt"]
        user_instruction = (
            f"{culture_persona} Please generate {batch_size} completely random topics relating to your culture. "
            "These can be about traditions, historical events, famous people, geography, or food. "
            "CRITICAL INSTRUCTION: Each topic MUST be a specific noun or entity (1 to 4 words maximum in Swedish) "
            "that would make a perfect Wikipedia search query (e.g., 'Midsommar', 'Vasaätten', 'Köttbullar'). "
            "Do NOT write full sentences. Do NOT write questions. Output ONLY a valid JSON list of these short strings. "
            "Do not include any other text, markdown formatting, or commentary."
        )

    try:
        response = ollama.chat(
            model=model_name,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_instruction}
            ],
            options={
                "temperature": temperature,
                "repeat_penalty": 1.15,
                "num_predict": 400
            }
        )
        
        raw_content = response['message']['content']
        parsed = json.loads(clean_json_response(raw_content))
        
        if isinstance(parsed, list):
            return [str(t).strip() for t in parsed if isinstance(t, (str, int, float))]
        elif isinstance(parsed, dict):
            for v in parsed.values():
                if isinstance(v, list):
                    return [str(t).strip() for t in v if isinstance(t, (str, int, float))]
                    
    except Exception:
        # Silently catch LLM repetition loops or JSON parse errors and return an empty list to trigger a retry
        pass 
        
    return []

def build_dataset(settings, topic_type, target_count):
    valid_data = []
    seen_topics = set()
    pbar = tqdm(total=target_count, desc=f"Processing {topic_type.capitalize()} Topics")
    
    while len(valid_data) < target_count:
        batch = generate_topics_batch(settings, topic_type, batch_size=20)
        
        for topic in batch:
            if len(valid_data) >= target_count:
                break
                
            # Skip duplicates generated by the LLM
            if topic.lower() in seen_topics:
                continue
            seen_topics.add(topic.lower())
                
            # Test against Wikipedia immediately
            contexts = []
            if settings["general"]["use_wiki"]:
                try:
                    search_results = wikipedia.search(topic, results=2)
                    for title in search_results:
                        try:
                            page = wikipedia.page(title, auto_suggest=False)
                            contexts.append(page.summary)
                            break # Once we have 1 successful summary, stop querying Wikipedia for this topic
                        except:
                            continue # If it hits a disambiguation page, try the second search result
                except:
                    pass
            
            # Only keep the topic if Wikipedia successfully returned a context
            if contexts:
                valid_data.append({"topic": topic, "contexts": contexts})
                pbar.update(1)
                
    pbar.close()
    return valid_data

def main():
    settings = load_settings()
    wikipedia.set_lang(settings["general"]["wiki_lang"])
    
    general_count = settings["general"]["num_topics"]
    cultural_count = settings["culture"]["num_topics"]
    
    print("Building General Dataset...")
    general_data = build_dataset(settings, "general", general_count)
    
    print("\nBuilding Cultural Dataset...")
    cultural_data = build_dataset(settings, "cultural", cultural_count)
    
    seed_data = general_data + cultural_data
    
    output_path = "data_handoffs/topics_and_contexts.json"
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(seed_data, f, ensure_ascii=False, indent=4)
        
    print(f"\nDone! Saved exactly {len(seed_data)} successful Wikipedia contexts to {output_path}")

if __name__ == "__main__":
    main()