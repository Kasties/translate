#!/usr/bin/env bash
# rn2 source ablation: the rn2-hplt setup, one seed source at a time.
#   Ahmad's parts: fineweb, cultura, riksdagen, and the cultura+wiki+riksdagen mix.
#   HPLT sources: news, forum, web (rn2-hplt from run_rn2_suite.sh is their equal mix).
#   1. Generate each condition (data -> $UPLOAD_REPO).
#   2. Draw a 125k-supervised-token subset of each.
#   3. Train every condition with seeds 42, 43, 44.
#   4. Full evaluation, minimal pairs + skolprov only, seed 42 of every condition first.
# The base model and rn2-hplt were already evaluated by run_rn2_suite.sh on the same datasets.
# Safe to rerun: finished steps leave a marker in artifacts/rn2-sources/done/ and are skipped.
#   source ~/.local/share/s2s-env.sh
#   bash scripts/run_rn2_sources.sh
set -euo pipefail
cd "$(dirname "$0")/.."
UPLOAD_REPO=${UPLOAD_REPO:-Sinall/tdde}
BUDGET=125000
SEEDS=(42 43 44)
CONDITIONS=(rn2-ahmad-fineweb rn2-ahmad-cultura rn2-ahmad-riksdagen rn2-ahmad-mix rn2-hplt-news rn2-hplt-forum rn2-hplt-web)
DONE=artifacts/rn2-sources/done
mkdir -p "$DONE"

step() {  # step <marker> <command...>: run once, then remember it
    local marker=$DONE/$1; shift
    if [[ -f $marker ]]; then echo "--- $(basename "$marker"): done, skipping"; return; fi
    check_booking
    echo "--- $(basename "$marker"): $(date '+%F %H:%M')"
    "$@"
    date '+%F %H:%M' > "$marker"
}

check_booking() {
    local file=/etc/stellar/booking.json
    [[ -s $file ]] || return 0
    python3 - "$file" <<'EOF' || { echo "Machine booked by someone else; stopping. Rerun when it is free."; exit 3; }
import json, os, sys
booking = json.load(open(sys.argv[1]))
sys.exit(0 if not booking or booking.get("account") == os.environ["USER"] or booking.get("shared") else 1)
EOF
}

subset() {  # subset <name>
    .venv-train/bin/python scripts/baselines/match_tokens.py --count answer --budget-tokens $BUDGET \
        --reference "artifacts/source2synth/runs/$1/train.jsonl" \
        --baseline "$1-125k=artifacts/source2synth/runs/$1/train.jsonl" --output "artifacts/subsets/$1"
    .venv/bin/hf upload "$UPLOAD_REPO" "artifacts/subsets/$1" "$1/data/subset-125k" --quiet
}

generate() {  # generate <condition>: a build that stops short of the target resumes with more batches
    local try
    for try in 1 2 3; do
        ./pipeline run "configs/pipeline/$1.yaml" --to generate && return 0
        echo "generation of $1 incomplete (try $try), rerunning to add batches"
    done
    return 1
}

run_name() { [[ $2 == 42 ]] && echo "$1" || echo "$1-s$2"; }

train() {  # train <condition> <seed>
    ./pipeline run "configs/pipeline/$1.yaml" --only sft --name "$(run_name "$1" "$2")" --set "sft.seed=$2"
}

evaluate() {  # evaluate <checkpoint folder> <training_data label>
    cat > "evaluation/$2_run.yaml" <<EOF
# Generated by scripts/run_rn2_sources.sh: full run of $2, minimal pairs + skolprov only.
full_run: true
upload: true
suites: [minimal-pair, euroeval]
euroeval_datasets: [skolprov]
models:
  - reference: $1
    model_family: google/gemma-4-12B
    training_data: $2
    training_method: lora
EOF
    (cd evaluation && uv run python -m evaluation run --config "$2_run.yaml")
}

eval_adapter() {  # eval_adapter <condition> <seed>
    local name merged
    name=$(run_name "$1" "$2")
    merged=/scratch/$USER/checkpoints/$name-merged
    .venv-train/bin/python scripts/dpo/merge_adapter.py "artifacts/finetuning/$name/adapter" "$merged"
    evaluate "$merged" "$name"
    rm -rf "$merged"
}

# 1. Generation (each build resumes if interrupted).
for condition in "${CONDITIONS[@]}"; do
    step "gen-$condition" generate "$condition"
done

# 2. Training sets at 125k supervised tokens.
for condition in "${CONDITIONS[@]}"; do
    step "subset-$condition" subset "$condition"
done

# 3. Training.
for seed in "${SEEDS[@]}"; do
    for condition in "${CONDITIONS[@]}"; do
        step "train-$(run_name "$condition" "$seed")" train "$condition" "$seed"
    done
done

# 4. Evaluation, seed by seed.
for seed in "${SEEDS[@]}"; do
    for condition in "${CONDITIONS[@]}"; do
        step "eval-$(run_name "$condition" "$seed")" eval_adapter "$condition" "$seed"
    done
done
echo "=== rn2 source ablation finished $(date '+%F %H:%M')"
