#!/usr/bin/env bash
# The rn2 suite: the fixes from the review of the first experiments, with training seeds and full
# EuroEval runs so the conditions can be told apart.
#   1. Generate rn2-hplt (Qwen reviewer) and rn2-hplt-judge (Qwen reviewer + judge); data -> $UPLOAD_REPO.
#   2. Draw 125k-supervised-token subsets of both and of MURI, and build the response-only control.
#   3. Train every condition with seeds 42, 43, 44 (adapters -> $UPLOAD_REPO, pipeline eval skipped).
#   4. Main's evaluation as a full run (test split, 10 iterations): the base model once, then seed
#      42 of every condition, then 43, then 44, so the first comparable results come early.
# Safe to rerun: every finished step leaves a marker in artifacts/rn2/done/ and is skipped.
# Before each GPU step it stops if someone else has booked the machine.
#   source ~/.local/share/s2s-env.sh
#   bash scripts/run_rn2_suite.sh
set -euo pipefail
cd "$(dirname "$0")/.."
UPLOAD_REPO=${UPLOAD_REPO:-Sinall/tdde}
BUDGET=125000
SEEDS=(42 43 44)
CONDITIONS=(rn2-hplt rn2-hplt-judge rn2-hplt-control rn2-muri)
TEMPLATE=artifacts/finetuning/register-native-gemma4-31b-gen/adapter
DONE=artifacts/rn2/done
mkdir -p "$DONE"

step() {  # step <marker> <command...>: run once, then remember it
    local marker=$DONE/$1; shift
    if [[ -f $marker ]]; then echo "--- $(basename "$marker"): done, skipping"; return; fi
    check_booking
    echo "--- $(basename "$marker"): $(date '+%F %H:%M')"
    "$@"
    date '+%F %H:%M' > "$marker"
}

check_booking() {
    local file=/etc/stellar/booking.json
    [[ -s $file ]] || return 0
    python3 - "$file" <<'EOF' || { echo "Machine booked by someone else; stopping. Rerun when it is free."; exit 3; }
import json, os, sys
booking = json.load(open(sys.argv[1]))
sys.exit(0 if not booking or booking.get("account") == os.environ["USER"] or booking.get("shared") else 1)
EOF
}

subset() {  # subset <name> <train.jsonl>
    .venv-train/bin/python scripts/baselines/match_tokens.py --count answer --budget-tokens $BUDGET \
        --reference "$2" --baseline "$1-125k=$2" --output "artifacts/subsets/$1"
    .venv/bin/hf upload "$UPLOAD_REPO" "artifacts/subsets/$1" "$1/data/subset-125k" --quiet
}

control() {
    mkdir -p artifacts/subsets/rn2-hplt-control
    python3 scripts/controls/generic_prompt.py --subset artifacts/subsets/rn2-hplt/rn2-hplt-125k.jsonl \
        --accepted artifacts/source2synth/runs/rn2-hplt/accepted.jsonl \
        --output artifacts/subsets/rn2-hplt-control/rn2-hplt-control-125k.jsonl
    .venv/bin/hf upload "$UPLOAD_REPO" artifacts/subsets/rn2-hplt-control rn2-hplt-control/data/subset-125k --quiet
}

run_name() { [[ $2 == 42 ]] && echo "$1" || echo "$1-s$2"; }

train() {  # train <condition> <seed>
    ./pipeline run "configs/pipeline/$1.yaml" --only sft --name "$(run_name "$1" "$2")" --set "sft.seed=$2"
}

evaluate() {  # evaluate <checkpoint folder> <training_data label> <config name>
    cat > "evaluation/$3_run.yaml" <<EOF
# Generated by scripts/run_rn2_suite.sh: full run of $2.
full_run: true
upload: true
models:
  - reference: $1
    model_family: google/gemma-4-12B
    training_data: $2
    training_method: $([[ $2 == none ]] && echo none || echo lora)
EOF
    (cd evaluation && uv run python -m evaluation run --config "$3_run.yaml")
}

base_checkpoint() {  # the base weights (symlinked) with the chat template the adapters were trained with
    local out=/scratch/$USER/checkpoints/gemma-4-12B-base-template
    rm -rf "$out"; mkdir -p "$out"
    local snapshot
    snapshot=$(.venv/bin/python -c "from huggingface_hub import snapshot_download as s; print(s('google/gemma-4-12B'))")
    ln -s "$snapshot"/* "$out"/
    for file in "$TEMPLATE"/{tokenizer.json,tokenizer_config.json,chat_template.jinja,special_tokens_map.json}; do
        [[ -e $file ]] && { rm -f "$out/$(basename "$file")"; cp "$file" "$out/"; }
    done
    echo "$out"
}

eval_base() {
    local checkpoint
    checkpoint=$(base_checkpoint | tail -1)
    evaluate "$checkpoint" none rn2-base
    rm -rf "$checkpoint"
}

eval_adapter() {  # eval_adapter <condition> <seed>
    local name merged
    name=$(run_name "$1" "$2")
    merged=/scratch/$USER/checkpoints/$name-merged
    .venv-train/bin/python scripts/dpo/merge_adapter.py "artifacts/finetuning/$name/adapter" "$merged"
    evaluate "$merged" "$name" "$name"
    rm -rf "$merged"
}

# 1. Generation (each build resumes if interrupted).
step gen-rn2-hplt ./pipeline run configs/pipeline/rn2-hplt.yaml --to generate
step gen-rn2-hplt-judge ./pipeline run configs/pipeline/rn2-hplt-judge.yaml --to generate

# 2. Training sets at 125k supervised tokens.
step subset-rn2-hplt subset rn2-hplt artifacts/source2synth/runs/rn2-hplt/train.jsonl
step subset-rn2-hplt-judge subset rn2-hplt-judge artifacts/source2synth/runs/rn2-hplt-judge/train.jsonl
step subset-rn2-muri subset rn2-muri artifacts/baselines/baselines/muri/data/processed/train.jsonl
step subset-rn2-hplt-control control

# 3. Training.
for seed in "${SEEDS[@]}"; do
    for condition in "${CONDITIONS[@]}"; do
        step "train-$(run_name "$condition" "$seed")" train "$condition" "$seed"
    done
done

# 4. Full evaluation, base first, then seed by seed.
step eval-base eval_base
for seed in "${SEEDS[@]}"; do
    for condition in "${CONDITIONS[@]}"; do
        step "eval-$(run_name "$condition" "$seed")" eval_adapter "$condition" "$seed"
    done
done
echo "=== rn2 suite finished $(date '+%F %H:%M')"
