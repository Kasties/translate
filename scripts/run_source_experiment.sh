#!/usr/bin/env bash
# Run one data-source experiment end to end, saving every result to Hugging Face as soon as it exists:
#   generate (data -> $UPLOAD_REPO/<name>/data/) -> 259k-token subset (uploaded next to it)
#   -> train + pipeline eval (adapter -> $UPLOAD_REPO/<name>/) -> merge -> main's evaluation
#   (results -> $RESULTS_REPO) -> delete the merged checkpoint.
# Safe to rerun after an interruption: finished stages are skipped, and a finished experiment is
# skipped entirely (artifacts/pipeline/<name>/experiment-done).
#   source ~/.local/share/s2s-env.sh
#   bash scripts/run_source_experiment.sh source-hplt-news [more names...]
set -euo pipefail
cd "$(dirname "$0")/.."
UPLOAD_REPO=${UPLOAD_REPO:-Sinall/tdde}
REFERENCE=artifacts/source2synth/runs/register-native-gemma4-31b-gen/train.jsonl

for name in "$@"; do
    done_marker=artifacts/pipeline/$name/experiment-done
    if [[ -f $done_marker ]]; then
        echo "=== $name: already finished, skipping"
        continue
    fi
    echo "=== $name: $(date '+%F %H:%M')"
    ./pipeline run "configs/pipeline/$name.yaml" --to generate

    subset_dir=artifacts/subsets/$name
    .venv-train/bin/python scripts/baselines/match_tokens.py --reference "$REFERENCE" \
        --baseline "$name-259k=artifacts/source2synth/runs/$name/train.jsonl" --output "$subset_dir"
    .venv/bin/hf upload "$UPLOAD_REPO" "$subset_dir" "$name/data/subset-259k" --quiet

    ./pipeline run "configs/pipeline/$name.yaml" --from sft

    merged=/scratch/$USER/checkpoints/$name-merged
    .venv-train/bin/python scripts/dpo/merge_adapter.py "artifacts/finetuning/$name/adapter" "$merged"
    cat > "evaluation/${name}_run.yaml" <<EOF
# Generated by scripts/run_source_experiment.sh: main's evaluation of $name.
upload: true
models:
  - reference: $merged
    model_family: google/gemma-4-12B
    training_data: $name
    training_method: lora
EOF
    (cd evaluation && uv run python -m evaluation run --config "${name}_run.yaml")
    rm -rf "$merged"
    date '+%F %H:%M' > "$done_marker"
    echo "=== $name: finished $(date '+%F %H:%M')"
done
